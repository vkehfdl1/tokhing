-- Additive admin-ops schema/RPCs.
-- Intentionally does NOT:
--   * revoke execute on existing season/market/grant RPCs
--   * replace login / execute_buy_order / execute_sell_order / activate_season
--   * run weekly grant cron or mutate wallets/markets/orders
--   * lock or delete games
-- Season 3 rows are left untouched.

do $$
begin
  create type public.admin_role as enum ('OWNER', 'OPERATOR', 'VIEWER');
exception
  when duplicate_object then null;
end;
$$;

create table if not exists public.admin_operators (
  id uuid primary key default gen_random_uuid(),
  username text not null,
  display_name text not null,
  role public.admin_role not null default 'VIEWER',
  password_hash text not null,
  is_active boolean not null default true,
  must_change_password boolean not null default true,
  created_by uuid references public.admin_operators(id) on delete set null,
  last_login_at timestamptz,
  password_changed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists admin_operators_username_lower_key
  on public.admin_operators (lower(username));

create table if not exists public.admin_sessions (
  id uuid primary key default gen_random_uuid(),
  operator_id uuid not null references public.admin_operators(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  reauthenticated_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  revoked_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
