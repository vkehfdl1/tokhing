create or replace function public.resolve_team_mappings(
  p_source text,
  p_external_names text[]
)
returns table (
  external_name text,
  mapping_status text,
  team_id integer,
  team_name text,
  request_id bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text;
  v_team public.teams;
  v_request_id bigint;
begin
  if btrim(coalesce(p_source, '')) = '' then
    raise exception '소스를 입력해주세요';
  end if;

  for v_name in
    select distinct btrim(value)
    from unnest(coalesce(p_external_names, array[]::text[])) as names(value)
    where btrim(value) <> ''
  loop
    select t.*
    into v_team
    from public.teams t
    where t.is_active
      and (
        lower(btrim(t.name)) = lower(v_name)
        or lower(btrim(t.short_name)) = lower(v_name)
      )
    limit 1;

    if not found then
      select t.*
      into v_team
      from public.team_aliases a
      join public.teams t on t.id = a.team_id
      where a.is_active
        and t.is_active
        and upper(btrim(a.source)) = upper(btrim(p_source))
        and a.normalized_alias = lower(v_name)
      limit 1;
    end if;

    if found then
      external_name := v_name;
      mapping_status := 'MAPPED';
      team_id := v_team.id;
      team_name := v_team.name;
      request_id := null;
      return next;
    else
      insert into public.team_mapping_requests (
        source, external_name, status
      )
      values (
        upper(btrim(p_source)), v_name, 'PENDING'
      )
      on conflict (
        (upper(btrim(source))),
        normalized_external_name
      ) where status = 'PENDING'
      do update
      set occurrence_count =
            public.team_mapping_requests.occurrence_count + 1,
          last_seen_at = now(),
          external_name = excluded.external_name
      returning id into v_request_id;

      external_name := v_name;
      mapping_status := 'PENDING';
      team_id := null;
      team_name := null;
      request_id := v_request_id;
      return next;
    end if;
  end loop;
end;
$$;

