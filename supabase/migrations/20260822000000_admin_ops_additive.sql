    balance_after,
    description,
    created_at
  )
  select
    u.id,
    v_target.id,
    'SEASON_GRANT',
    v_target.initial_grant_amount,
    v_target.initial_grant_amount,
    '시즌 시작 코인 지급',
    now()
  from public.users u;
