create or replace function public.preview_settlement_recovery(p_market_id integer)returns jsonb language sql security definer set search_path=public as $$select jsonb_build_object('event',to_jsonb(e),'shortages',coalesce((select jsonb_agg(jsonb_build_object('user_id',x.user_id,'payout',x.amount,'balance',w.balance,'shortage',greatest(x.amount-w.balance,0)))from jsonb_to_recordset(e.payout_snapshot)as x(transaction_id integer,user_id uuid,amount numeric)join wallets w on w.user_id=x.user_id and w.season_id=(select season_id from markets where id=e.market_id)where w.balance<x.amount),'[]'))from settlement_events e where market_id=p_market_id;$$;

create or replace function public.admin_recover_settlement(p_operator_id uuid,p_market_id integer,p_correct_result text,p_reason text)returns jsonb language plpgsql security definer set search_path=public as $$declare e settlement_events;r settlement_recoveries;x record;w wallets;p numeric;begin if btrim(coalesce(p_reason,''))=''then raise exception '복구 사유를 입력해주세요';end if;select*into e from settlement_events where market_id=p_market_id for update;if not found then raise exception '정산 이벤트를 찾을 수 없습니다';end if;if exists(select 1 from settlement_recoveries where event_id=e.id)then raise exception '이미 복구된 정산입니다';end if;for x in select*from jsonb_to_recordset(e.payout_snapshot)as q(transaction_id integer,user_id uuid,amount numeric)loop select*into w from wallets where user_id=x.user_id and season_id=(select season_id from markets where id=p_market_id)for update;if w.balance<x.amount then raise exception '보상 차감 잔액이 부족한 사용자가 있습니다';end if;update wallets set balance=balance-x.amount where id=w.id;insert into transactions(user_id,season_id,type,amount,balance_after,reference_id,description)values(x.user_id,w.season_id,'SETTLEMENT_REVERSAL',-x.amount,w.balance-x.amount,x.transaction_id,'정산 취소 보상');end loop;insert into settlement_recoveries(event_id,correct_result,reason,operator_id,status)values(e.id,p_correct_result,p_reason,p_operator_id,'SUCCESS')returning*into r;for x in select user_id,quantity from jsonb_to_recordset(e.position_snapshot)as q(user_id uuid,outcome text,quantity numeric)where outcome=p_correct_result loop p:=x.quantity*100;update wallets set balance=balance+p where user_id=x.user_id and season_id=(select season_id from markets where id=p_market_id)returning*into w;insert into transactions(user_id,season_id,type,amount,balance_after,reference_id,description)values(x.user_id,w.season_id,'SETTLEMENT_CORRECTION',p,w.balance,r.id,'정산 재처리 - '||p_correct_result);end loop;insert into admin_audit_logs(operator_id,action,target_type,target_id,before_state,after_state,success)values(p_operator_id,'SETTLEMENT_RECOVERY','market',p_market_id::text,to_jsonb(e),to_jsonb(r),true);return to_jsonb(r);end;$$;

