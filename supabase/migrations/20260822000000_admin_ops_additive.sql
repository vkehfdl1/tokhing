create or replace function public.preview_season_incident(p_season_id integer)returns jsonb language plpgsql security definer set search_path=public as $$declare n seasons;p seasons;begin select*into n from seasons where id=p_season_id;select*into p from seasons where status='ARCHIVED' and id<>n.id order by end_date desc nulls last limit 1;return jsonb_build_object('new_season',to_jsonb(n),'previous_season',to_jsonb(p),'counts',jsonb_build_object('wallets',(select count(*)from wallets where season_id=n.id),'orders',(select count(*)from orders where season_id=n.id),'positions',(select count(*)from positions where season_id=n.id),'markets',(select count(*)from markets where season_id=n.id),'transactions',(select count(*)from transactions where season_id=n.id)),'automatic_possible',not exists(select 1 from orders where season_id=n.id)and not exists(select 1 from transactions where season_id=n.id and type='SETTLEMENT'),'reason',case when exists(select 1 from orders where season_id=n.id)then'신규 시즌 주문 존재'when exists(select 1 from transactions where season_id=n.id and type='SETTLEMENT')then'신규 시즌 정산 존재'end);end;$$;

create or replace function public.admin_recover_season_incident(p_operator_id uuid,p_season_id integer,p_reason text)returns jsonb language plpgsql security definer set search_path=public as $$declare v jsonb;n seasons;p seasons;g record;w wallets;before jsonb;after jsonb;begin if btrim(coalesce(p_reason,''))=''then raise exception'복구 사유를 입력해주세요';end if;v:=preview_season_incident(p_season_id);if not(v->>'automatic_possible')::boolean then raise exception'자동 복구가 불가능합니다';end if;select*into n from seasons where id=p_season_id and status='ACTIVE'for update;select*into p from seasons where id=(v->'previous_season'->>'id')::integer for update;before:=jsonb_build_object('new',to_jsonb(n),'previous',to_jsonb(p));for g in select*from transactions where season_id=n.id and type='SEASON_GRANT'loop select*into w from wallets where user_id=g.user_id and season_id=n.id for update;if w.balance<g.amount then raise exception'시즌 지급 보상 차감 잔액 부족';end if;update wallets set balance=balance-g.amount where id=w.id;insert into transactions(user_id,season_id,type,amount,balance_after,reference_id,description)values(g.user_id,n.id,'SEASON_GRANT_REVERSAL',-g.amount,w.balance-g.amount,g.id,'시즌 활성화 취소 보상');end loop;update seasons set status='DRAFT'where id=n.id;update seasons set status='ACTIVE',end_date=null where id=p.id;after:=jsonb_build_object('new',(select to_jsonb(s)from seasons s where id=n.id),'previous',(select to_jsonb(s)from seasons s where id=p.id));insert into season_incidents(new_season_id,previous_season_id,reason,operator_id,before_state,after_state)values(n.id,p.id,p_reason,p_operator_id,before,after);insert into admin_audit_logs(operator_id,action,target_type,target_id,before_state,after_state,success)values(p_operator_id,'SEASON_INCIDENT_RECOVERY','season',n.id::text,before,after,true);if(select count(*)from seasons where status='ACTIVE')<>1 then raise exception'ACTIVE 시즌은 정확히 하나여야 합니다';end if;return after;end;$$;


