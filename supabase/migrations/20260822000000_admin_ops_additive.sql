create or replace function public.run_weekly_grant_round(
  p_operator_id uuid,
  p_round_key text,
  p_source text,
  p_scheduled_for timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_policy public.weekly_grant_policies;
  v_season public.seasons;
  v_run public.weekly_grant_runs;
  v_recipient_count integer;
  v_total numeric;
begin
  if btrim(coalesce(p_round_key, '')) = '' then
    raise exception '지급 라운드를 입력해주세요';
  end if;
  if upper(p_source) not in ('AUTO', 'MANUAL') then
    raise exception '지급 실행 구분이 올바르지 않습니다';
  end if;
  select * into v_season from public.seasons where status = 'ACTIVE' limit 1;
  if not found then raise exception '활성 시즌이 없습니다'; end if;
  select * into v_policy from public.weekly_grant_policies
  where season_id = v_season.id;

  insert into public.weekly_grant_runs (
    season_id, round_key, source, status, scheduled_for, initiated_by
  ) values (
    v_season.id, btrim(p_round_key), upper(p_source), 'RUNNING',
    p_scheduled_for, p_operator_id
  )
  on conflict (season_id, round_key) do nothing;

  select * into v_run from public.weekly_grant_runs
  where season_id = v_season.id and round_key = btrim(p_round_key)
  for update;

  if v_run.status = 'SUCCESS' then
    return jsonb_build_object(
      'status', 'SKIPPED', 'run_id', v_run.id,
      'round_key', v_run.round_key, 'message', '이미 지급된 라운드입니다'
    );
  end if;
  if upper(p_source) = 'AUTO'
    and (not v_policy.automatic_enabled or v_policy.is_paused) then
    update public.weekly_grant_runs
    set status = 'SKIPPED', completed_at = now(),
        error_message = '자동 지급이 일시정지되었습니다'
    where id = v_run.id;
    return jsonb_build_object(
      'status', 'SKIPPED', 'run_id', v_run.id,
      'round_key', v_run.round_key,
      'message', '자동 지급이 일시정지되었습니다'
    );
  end if;

  update public.weekly_grant_runs
  set source = upper(p_source), status = 'RUNNING',
      initiated_by = p_operator_id, started_at = now(),
      completed_at = null, error_message = null
  where id = v_run.id;

  begin
    insert into public.wallets (user_id, season_id, balance)
    select id, v_season.id, 0 from public.users
    on conflict (user_id, season_id) do nothing;

    with updated as (
      update public.wallets w
      set balance = w.balance + v_policy.amount, updated_at = now()
      where w.season_id = v_season.id
      returning w.user_id, w.balance
    ), recipient_rows as (
      insert into public.weekly_grant_run_recipients (
        run_id, user_id, amount, balance_after
      )
      select v_run.id, user_id, v_policy.amount, balance from updated
      returning user_id, balance_after
    ), transaction_rows as (
      insert into public.transactions (
        user_id, type, amount, balance_after, reference_id,
        description, season_id
      )
      select user_id, 'WEEKLY_GRANT', v_policy.amount, balance_after,
        v_run.id, '주간 코인 지급 ' || btrim(p_round_key), v_season.id
      from recipient_rows
      returning user_id
    )
    select count(*), count(*) * v_policy.amount
    into v_recipient_count, v_total
    from transaction_rows;

    update public.weekly_grant_runs
    set status = 'SUCCESS', recipient_count = v_recipient_count,
        total_payout = v_total, failure_count = 0, completed_at = now()
    where id = v_run.id;
  exception when others then
    update public.weekly_grant_runs
    set status = 'FAILURE', failure_count = 1,
        error_message = sqlerrm, completed_at = now()
    where id = v_run.id;
    insert into public.admin_audit_logs (
      operator_id, action, target_type, target_id, after_state, success,
      error_message
    ) values (
      p_operator_id, 'WEEKLY_GRANT_' || upper(p_source) || '_RUN',
      'weekly_grant_run', v_run.id::text,
      jsonb_build_object('round_key', p_round_key, 'status', 'FAILURE'),
      false, sqlerrm
    );
    return jsonb_build_object(
      'status', 'FAILURE', 'run_id', v_run.id,
      'round_key', p_round_key, 'error', sqlerrm
    );
  end;

  insert into public.admin_audit_logs (
    operator_id, action, target_type, target_id, after_state, success
  ) values (
    p_operator_id, 'WEEKLY_GRANT_' || upper(p_source) || '_RUN',
    'weekly_grant_run', v_run.id::text,
    jsonb_build_object(
      'round_key', p_round_key, 'status', 'SUCCESS',
      'recipient_count', v_recipient_count, 'total_payout', v_total
    ), true
  );
  return jsonb_build_object(
    'status', 'SUCCESS', 'run_id', v_run.id,
    'round_key', p_round_key, 'recipient_count', v_recipient_count,
    'total_payout', v_total
  );
end;
$$;

