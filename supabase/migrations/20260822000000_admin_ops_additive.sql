create or replace function public.weekly_grant_cron_expression(
  p_weekday integer,
  p_grant_time time
)
returns text
language plpgsql
immutable
as $$
declare
  v_kst_dow integer;
  v_utc_dow integer;
  v_hour integer;
  v_minute integer;
begin
  if p_weekday not between 1 and 7 then
    raise exception '요일은 1(월)부터 7(일) 사이여야 합니다';
  end if;
  v_hour := extract(hour from p_grant_time)::integer;
  v_minute := extract(minute from p_grant_time)::integer;
  v_kst_dow := p_weekday % 7;
  v_utc_dow := (v_kst_dow - case when v_hour < 9 then 1 else 0 end + 7) % 7;
  return format(
    '%s %s * * %s',
    v_minute,
    (v_hour + 15) % 24,
    v_utc_dow
  );
end;
$$;

