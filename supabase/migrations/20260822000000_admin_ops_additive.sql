    v_policy.grant_time
  );
  select jobid into v_job_id
  from cron.job
  where jobname = 'weekly_coin_distribution';

  if v_job_id is null then
    perform cron.schedule(
      'weekly_coin_distribution',
      v_schedule,
      'SELECT public.run_scheduled_weekly_grant();'
    );
    select jobid into v_job_id
    from cron.job
    where jobname = 'weekly_coin_distribution';
  end if;

  perform cron.alter_job(
    v_job_id,
    schedule := v_schedule,
    command := 'SELECT public.run_scheduled_weekly_grant();',
    active := v_policy.automatic_enabled and not v_policy.is_paused
  );
end;
$$;

create or replace function public.get_weekly_grant_status()
returns jsonb
language plpgsql
security definer
set search_path = public, cron
as $$
declare
  v_policy public.weekly_grant_policies;
  v_season public.seasons;
  v_recipient_count integer;
  v_job cron.job;
  v_runs jsonb;
begin
  select * into v_season
  from public.seasons where status = 'ACTIVE' limit 1;
  if not found then
    raise exception '활성 시즌이 없습니다';
  end if;

  select * into v_policy
  from public.weekly_grant_policies
  where season_id = v_season.id;
  if not found then
    raise exception '주간 지급 정책을 찾을 수 없습니다';
  end if;

  select count(*) into v_recipient_count from public.users;
  select * into v_job
  from cron.job where jobname = 'weekly_coin_distribution';
  select coalesce(jsonb_agg(to_jsonb(r) order by r.started_at desc), '[]'::jsonb)
  into v_runs
  from (
    select id, round_key, source, status, scheduled_for,
      recipient_count, total_payout, failure_count,
      error_message, started_at, completed_at
    from public.weekly_grant_runs
    where season_id = v_season.id
    order by started_at desc
    limit 10
  ) r;

  return jsonb_build_object(
    'season_id', v_season.id,
    'season_name', v_season.name,
    'amount', v_policy.amount,
    'weekday', v_policy.weekday,
    'grant_time', to_char(v_policy.grant_time, 'HH24:MI'),
    'automatic_enabled', v_policy.automatic_enabled,
    'is_paused', v_policy.is_paused,
    'cron_expression', public.weekly_grant_cron_expression(
      v_policy.weekday, v_policy.grant_time
    ),
    'cron_active', coalesce(v_job.active, false),
    'next_run', case
      when v_policy.automatic_enabled and not v_policy.is_paused
      then public.weekly_grant_next_run(v_policy.weekday, v_policy.grant_time)
      else null
    end,
    'expected_recipient_count', v_recipient_count,
    'estimated_total_payout', v_recipient_count * v_policy.amount,
    'recent_runs', v_runs
  );
end;
$$;

