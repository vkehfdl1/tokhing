create table public.kbo_sync_jobs (
  mode text primary key check (mode in ('DAILY_SEED','HOURLY_REFRESH')),
  status text not null default 'ACTIVE' check (status in ('ACTIVE','PAUSED','DISABLED')),
  schedule_kst time not null,
  enabled boolean not null default true,
  updated_at timestamptz not null default now()
);
create table public.kbo_sync_runs (
  id integer generated by default as identity primary key,
  mode text not null references public.kbo_sync_jobs(mode),
  target_date date not null,
  initial_price numeric not null,
  attempt integer not null default 1,
  status text not null check (status in ('SUCCESS','FAILURE')),
  error_code text,
  matches_created integer not null default 0,
  matches_updated integer not null default 0,
  skipped_items integer not null default 0,
  markets_created integer not null default 0,
  markets_closed integer not null default 0,
  error_count integer not null default 0,
  missing_candidates jsonb not null default '[]',
  duplicate_candidates jsonb not null default '[]',
  initiated_by uuid references public.admin_operators(id),
  created_at timestamptz not null default now(),
  unique(mode,target_date,initial_price,attempt)
);
create table public.kbo_sync_secret_status (
  id boolean primary key default true check (id),
  configured boolean not null default false,
  last_rotated_at timestamptz
);
