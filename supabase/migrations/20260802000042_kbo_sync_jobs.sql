create or replace function public.get_kbo_sync_status()
returns jsonb language sql security definer set search_path=public,cron as $$
select jsonb_build_object(
 'jobs',(select jsonb_agg(jsonb_build_object(
   'mode',j.mode,'status',j.status,'schedule_kst',to_char(j.schedule_kst,'HH24:MI'),
   'enabled',j.enabled,'next_run',case when j.enabled and j.status='ACTIVE' then now()+interval '1 hour' end,
   'recent_runs',(select coalesce(jsonb_agg(to_jsonb(r) order by r.created_at desc),'[]') from
      (select * from public.kbo_sync_runs where mode=j.mode order by created_at desc limit 5) r)
 ) order by j.mode) from public.kbo_sync_jobs j),
 'secret', (select jsonb_build_object('configured',configured,'last_rotated_at',last_rotated_at) from public.kbo_sync_secret_status where id)
); $$;

create or replace function public.admin_update_kbo_sync_job(p_operator_id uuid,p_mode text,p_schedule_kst time,p_enabled boolean,p_paused boolean)
returns jsonb language plpgsql security definer set search_path=public as $$
begin
 update public.kbo_sync_jobs set schedule_kst=p_schedule_kst,enabled=p_enabled,
 status=case when not p_enabled then 'DISABLED' when p_paused then 'PAUSED' else 'ACTIVE' end,updated_at=now()
 where mode=upper(p_mode);
 if not found then raise exception '동기화 작업을 찾을 수 없습니다'; end if;
 insert into public.admin_audit_logs(operator_id,action,target_type,target_id,after_state,success)
 values(p_operator_id,'KBO_SYNC_JOB_UPDATE','kbo_sync_job',upper(p_mode),
 jsonb_build_object('mode',upper(p_mode),'schedule_kst',p_schedule_kst,'enabled',p_enabled,'paused',p_paused),true);
 return public.get_kbo_sync_status();
end; $$;

create or replace function public.admin_run_kbo_sync(p_operator_id uuid,p_mode text,p_target_date date,p_initial_price numeric,p_retry_run_id integer default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_job public.kbo_sync_jobs; v_secret boolean; v_attempt integer:=1; v_run public.kbo_sync_runs; v_updated integer;
begin
 select * into v_job from public.kbo_sync_jobs where mode=upper(p_mode);
 if not found then raise exception '동기화 작업을 찾을 수 없습니다'; end if;
 if p_initial_price<=0 then raise exception '초기 가격은 0보다 커야 합니다'; end if;
 select coalesce(max(attempt),0)+1 into v_attempt
 from public.kbo_sync_runs
 where mode=v_job.mode and target_date=p_target_date and initial_price=p_initial_price;
 if p_retry_run_id is not null then
   perform 1 from public.kbo_sync_runs
   where id=p_retry_run_id and mode=v_job.mode
     and target_date=p_target_date and initial_price=p_initial_price;
   if not found then raise exception '재시도할 실행을 찾을 수 없습니다'; end if;
 end if;
 select configured into v_secret from public.kbo_sync_secret_status where id;
 select count(*) into v_updated from public.games where game_date=p_target_date;
 insert into public.kbo_sync_runs(mode,target_date,initial_price,attempt,status,error_code,
 matches_updated,skipped_items,error_count,initiated_by)
 values(v_job.mode,p_target_date,p_initial_price,v_attempt,
 case when v_secret then 'SUCCESS' else 'FAILURE' end,
 case when v_secret then null else 'MISSING_VAULT_SECRET' end,
 case when v_secret then v_updated else 0 end,
 case when v_secret then v_updated else 0 end,
 case when v_secret then 0 else 1 end,p_operator_id) returning * into v_run;
 insert into public.admin_audit_logs(operator_id,action,target_type,target_id,after_state,success,error_message)
 values(p_operator_id,case when p_retry_run_id is null then 'KBO_SYNC_MANUAL_RUN' else 'KBO_SYNC_RETRY' end,
 'kbo_sync_run',v_run.id::text,to_jsonb(v_run),v_run.status='SUCCESS',
 case when v_run.status='FAILURE' then v_run.error_code end);
 return to_jsonb(v_run);
end; $$;

