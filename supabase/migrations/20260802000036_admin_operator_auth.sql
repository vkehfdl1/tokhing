create or replace function public.admin_reserve_login_limit(
  p_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_limit public.admin_login_rate_limits;
  v_failed_attempts integer;
  v_retry_after integer;
begin
  select *
  into v_limit
  from public.admin_login_rate_limits
  where identity = p_key;

  if found
    and v_limit.blocked_until is not null
    and v_limit.blocked_until > now()
  then
    v_retry_after := greatest(
      1,
      ceil(
        extract(epoch from (v_limit.blocked_until - now()))
      )::integer
    );
    return jsonb_build_object(
      'allowed', false,
      'retryAfterSeconds', v_retry_after
    );
  end if;

  if not found then
    insert into public.admin_login_rate_limits (
      identity,
      failed_attempts,
      window_started_at,
      blocked_until
    )
    values (p_key, 0, now(), null)
    returning * into v_limit;
  elsif v_limit.window_started_at < now() - interval '15 minutes' then
    update public.admin_login_rate_limits
    set
      failed_attempts = 0,
      window_started_at = now(),
      blocked_until = null,
      updated_at = now()
    where identity = p_key
    returning * into v_limit;
  end if;

  v_failed_attempts := v_limit.failed_attempts + 1;
  update public.admin_login_rate_limits
  set
    failed_attempts = v_failed_attempts,
    blocked_until = case
      when v_failed_attempts >= 5
        then now() + interval '15 minutes'
      else null
    end,
    updated_at = now()
  where identity = p_key;

  return jsonb_build_object(
    'allowed', true,
    'attemptNumber', v_failed_attempts,
    'retryAfterSeconds', 0
  );
end;
$$;

create or replace function public.admin_begin_login_attempt(
  p_identity text,
  p_username text,
  p_ip_address inet,
  p_user_agent text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_account_key text;
  v_ip_key text;
  v_first_key text;
  v_second_key text;
  v_known_account boolean;
  v_limit_count integer;
  v_account_result jsonb;
  v_ip_result jsonb;
  v_blocked_key text;
  v_retry_after integer;
  v_attempt_id bigint;
begin
  select exists (
    select 1
    from public.admin_operators
    where lower(username) = lower(btrim(p_username))
  )
  into v_known_account;

  if v_known_account then
    v_account_key := 'account:' || lower(btrim(p_username));
  end if;
  v_ip_key := case
    when p_ip_address is null then 'ip:unknown'
    when family(p_ip_address) = 4 then
      'ip:' || host(network(set_masklen(p_ip_address, 24)))
    else
      'ip:' || host(network(set_masklen(p_ip_address, 64)))
  end;

  delete from public.admin_login_rate_limits
  where ctid in (
    select ctid
    from public.admin_login_rate_limits
    where updated_at < now() - interval '24 hours'
    order by updated_at
    limit 1000
  );

  if not v_known_account
    and not exists (
      select 1
      from public.admin_login_rate_limits
      where identity = v_ip_key
    )
  then
    perform pg_advisory_xact_lock(
      hashtextextended('admin-login-limit-cap', 0)
    );
    select count(*)
    into v_limit_count
    from public.admin_login_rate_limits;
    if v_limit_count >= 10000 then
      v_ip_key := 'ip:overflow';
    end if;
  end if;

  v_first_key := case
    when v_account_key is null then v_ip_key
    else least(v_account_key, v_ip_key)
  end;
  v_second_key := case
    when v_account_key is null then v_ip_key
    else greatest(v_account_key, v_ip_key)
  end;
  perform pg_advisory_xact_lock(
    hashtextextended(v_first_key, 0)
  );
  if v_second_key <> v_first_key then
    perform pg_advisory_xact_lock(
      hashtextextended(v_second_key, 0)
    );
  end if;

  if v_known_account then
    v_account_result :=
      public.admin_reserve_login_limit(v_account_key);
    if not (v_account_result ->> 'allowed')::boolean then
      v_blocked_key := v_account_key;
      v_retry_after :=
        (v_account_result ->> 'retryAfterSeconds')::integer;
    end if;
  end if;

  if v_blocked_key is null then
    v_ip_result := public.admin_reserve_login_limit(v_ip_key);
    if not (v_ip_result ->> 'allowed')::boolean then
      v_blocked_key := v_ip_key;
      v_retry_after :=
        (v_ip_result ->> 'retryAfterSeconds')::integer;
    end if;
  end if;

  if v_blocked_key is not null then
    if not exists (
      select 1
      from public.admin_audit_logs
      where action = 'ADMIN_LOGIN_BLOCKED'
        and target_id = v_blocked_key
        and created_at > now() - interval '1 minute'
    ) then
      insert into public.admin_audit_logs (
        action,
        target_type,
        target_id,
        after_state,
        success,
        error_message,
        ip_address,
        user_agent
      )
      values (
        'ADMIN_LOGIN_BLOCKED',
        'admin_login_limit',
        v_blocked_key,
        jsonb_build_object(
          'identity', p_identity,
          'accountKey', v_account_key,
          'ipKey', v_ip_key
        ),
        false,
        '로그인 시도 횟수를 초과했습니다.',
        p_ip_address,
        p_user_agent
      );
    end if;
    return jsonb_build_object(
      'allowed', false,
      'retryAfterSeconds', v_retry_after
    );
  end if;

  insert into public.admin_audit_logs (
    action,
    target_type,
    target_id,
    after_state,
    success,
    error_message,
    ip_address,
    user_agent
  )
  values (
    'ADMIN_LOGIN_ATTEMPT',
    'admin_operator',
    p_username,
    jsonb_build_object(
      'identity', p_identity,
      'accountKey', v_account_key,
      'ipKey', v_ip_key,
      'accountAttempt',
      v_account_result -> 'attemptNumber',
      'ipAttempt',
      v_ip_result -> 'attemptNumber'
    ),
    false,
    'AUTHENTICATION_PENDING',
    p_ip_address,
    p_user_agent
  )
  returning id into v_attempt_id;

  return jsonb_build_object(
    'allowed', true,
    'attemptId', v_attempt_id,
    'retryAfterSeconds', 0
  );
end;
$$;

