      'ip:' || host(network(set_masklen(p_ip_address, 64)))
  end;
  v_first_key := least(v_account_key, v_ip_key);
  v_second_key := greatest(v_account_key, v_ip_key);
  perform pg_advisory_xact_lock(
    hashtextextended(v_first_key, 0)
