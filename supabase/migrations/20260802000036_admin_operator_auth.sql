create or replace function public.admin_login_rate_limit_status(
  p_identity text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_limit public.admin_login_rate_limits;
  v_retry_after integer;
begin
  select *
  into v_limit
  from public.admin_login_rate_limits
  where identity = p_identity;

  if not found or v_limit.blocked_until is null
    or v_limit.blocked_until <= now()
  then
    return jsonb_build_object(
      'allowed', true,
      'retryAfterSeconds', 0
    );
  end if;

  v_retry_after := greatest(
    1,
    ceil(
      extract(epoch from (v_limit.blocked_until - now()))
    )::integer
  );
  return jsonb_build_object(
    'allowed', false,
    'retryAfterSeconds', v_retry_after
  );
end;
$$;

create or replace function public.admin_record_login_attempt(
  p_identity text,
  p_success boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_limit public.admin_login_rate_limits;
  v_failed_attempts integer;
begin
  if p_success then
    delete from public.admin_login_rate_limits
    where identity = p_identity;
    return jsonb_build_object(
      'allowed', true,
      'retryAfterSeconds', 0
    );
  end if;

  select *
  into v_limit
  from public.admin_login_rate_limits
  where identity = p_identity
  for update;

  if not found then
    insert into public.admin_login_rate_limits (
      identity,
      failed_attempts,
      window_started_at,
      blocked_until
    )
    values (
      p_identity,
      1,
      now(),
      null
    );
    return jsonb_build_object(
      'allowed', true,
      'retryAfterSeconds', 0
    );
  end if;

  if v_limit.blocked_until is not null
    and v_limit.blocked_until > now()
  then
    return public.admin_login_rate_limit_status(p_identity);
  end if;

  if v_limit.window_started_at < now() - interval '15 minutes' then
    v_failed_attempts := 1;
    update public.admin_login_rate_limits
    set
      failed_attempts = v_failed_attempts,
      window_started_at = now(),
      blocked_until = null,
      updated_at = now()
    where identity = p_identity;
  else
    v_failed_attempts := v_limit.failed_attempts + 1;
    update public.admin_login_rate_limits
    set
      failed_attempts = v_failed_attempts,
      blocked_until = case
        when v_failed_attempts >= 5 then now() + interval '15 minutes'
        else null
      end,
      updated_at = now()
    where identity = p_identity;
  end if;

  return public.admin_login_rate_limit_status(p_identity);
end;
$$;

