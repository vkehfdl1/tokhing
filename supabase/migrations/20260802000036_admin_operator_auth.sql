create or replace function public.lock_game_date_mutation()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_first_date date;
  v_second_date date;
begin
  if tg_op = 'INSERT' then
    perform pg_advisory_xact_lock(
      hashtextextended(
        'admin-game-date:' || new.game_date::text,
        0
      )
    );
    return new;
  end if;

  if tg_op = 'DELETE' then
    perform pg_advisory_xact_lock(
      hashtextextended(
        'admin-game-date:' || old.game_date::text,
        0
      )
    );
    return old;
  end if;

  v_first_date := least(old.game_date, new.game_date);
  v_second_date := greatest(old.game_date, new.game_date);
  perform pg_advisory_xact_lock(
    hashtextextended(
      'admin-game-date:' || v_first_date::text,
      0
    )
  );
  if v_second_date <> v_first_date then
    perform pg_advisory_xact_lock(
      hashtextextended(
        'admin-game-date:' || v_second_date::text,
        0
      )
    );
  end if;
  return new;
end;
$$;

