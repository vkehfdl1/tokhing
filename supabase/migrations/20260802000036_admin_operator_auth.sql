create or replace function public.admin_execute_rpc(
  p_operator_id uuid,
  p_action text,
  p_args jsonb,
  p_ip_address inet,
  p_user_agent text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_result jsonb;
  v_error text;
begin
  begin
    if not exists (
      select 1
      from public.admin_operators
      where id = p_operator_id
        and is_active
        and not must_change_password
        and role in ('OWNER', 'OPERATOR')
    ) then
      raise exception '관리자 변경 권한이 없습니다';
    end if;

    case p_action
      when 'create_season' then
        v_result := public.create_season(
          p_args ->> 'p_name',
          (p_args ->> 'p_start_date')::date,
          (p_args ->> 'p_end_date')::date
        );
      when 'activate_season' then
        v_result := public.activate_season(
          (p_args ->> 'p_season_id')::integer
        );
      when 'end_season' then
        v_result := public.end_season(
          (p_args ->> 'p_season_id')::integer
        );
      when 'create_market' then
        v_result := public.create_market(
          (p_args ->> 'p_game_id')::integer,
          (p_args ->> 'p_initial_home')::numeric,
          (p_args ->> 'p_initial_away')::numeric,
          (p_args ->> 'p_initial_draw')::numeric
        );
      when 'settle_market' then
        v_result := public.settle_market(
          (p_args ->> 'p_market_id')::integer,
          p_args ->> 'p_result'
        );
      when 'close_market' then
        v_result := public.close_market(
          (p_args ->> 'p_market_id')::integer
        );
      when 'cancel_market' then
        v_result := public.cancel_market(
          (p_args ->> 'p_market_id')::integer
        );
      when 'set_liquidity_b' then
        v_result := public.set_liquidity_b(
          (p_args ->> 'p_b')::numeric
        );
      when 'distribute_weekly_coins' then
        v_result := public.distribute_weekly_coins(
          (p_args ->> 'p_amount')::numeric
        );
      when 'admin_grant_coins' then
        v_result := public.admin_grant_coins(
          (p_args ->> 'p_user_id')::uuid,
          (p_args ->> 'p_amount')::numeric
        );
      when 'admin_reset_password' then
        v_result := public.admin_reset_password(
          (p_args ->> 'p_student_number')::bigint
        );
      when 'get_weekly_coin_cron_status' then
        v_result := public.get_weekly_coin_cron_status();
      else
        raise exception '지원하지 않는 관리자 작업입니다: %', p_action;
    end case;
  exception
    when others then
      get stacked diagnostics v_error = message_text;
      perform public.admin_write_audit(
        p_operator_id,
        'ADMIN_RPC_' || upper(p_action),
        'rpc',
        p_action,
        jsonb_build_object('args', p_args),
        null,
        false,
        v_error,
        p_ip_address,
        p_user_agent
      );
      return jsonb_build_object(
        'success', false,
        'error', v_error
      );
  end;

  perform public.admin_write_audit(
    p_operator_id,
    'ADMIN_RPC_' || upper(p_action),
    'rpc',
    p_action,
    jsonb_build_object('args', p_args),
    jsonb_build_object('result', v_result),
    true,
    null,
    p_ip_address,
    p_user_agent
  );

  return jsonb_build_object(
    'success', true,
    'data', v_result
  );
end;
$$;

create or replace function public.admin_apply_game_data(
  p_operator_id uuid,
  p_payload jsonb,
  p_ip_address inet,
  p_user_agent text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_action text := p_payload ->> 'action';
  v_before jsonb;
  v_after jsonb;
  v_error text;
  v_game jsonb;
  v_game_id integer;
  v_target_date date;
  v_keep_ids integer[];
  v_inserted_ids integer[] := array[]::integer[];
  v_deleted_ids integer[] := array[]::integer[];
begin
  begin
    if not exists (
      select 1
      from public.admin_operators
      where id = p_operator_id
        and is_active
        and not must_change_password
        and role in ('OWNER', 'OPERATOR')
    ) then
      raise exception '관리자 변경 권한이 없습니다';
    end if;

    if v_action = 'create_teams' then
      with inserted as (
        insert into public.teams (name, short_name, team_color)
        select
          team ->> 'name',
          team ->> 'short_name',
          team ->> 'team_color'
        from jsonb_array_elements(p_payload -> 'teams') as team
        returning id, name, short_name, team_color
      )
      select coalesce(jsonb_agg(to_jsonb(inserted)), '[]'::jsonb)
      into v_after
      from inserted;

      perform public.admin_write_audit(
        p_operator_id,
        'ADMIN_TEAMS_CREATED',
        'team',
        null,
        null,
        v_after,
        true,
        null,
        p_ip_address,
        p_user_agent
      );
      return jsonb_build_object('success', true, 'teams', v_after);
    end if;

    if v_action <> 'save_games' then
      raise exception '지원하지 않는 경기 데이터 작업입니다';
    end if;

    v_target_date := (p_payload ->> 'targetDate')::date;
    perform pg_advisory_xact_lock(
      hashtextextended(
        'admin-game-date:' || v_target_date::text,
        0
      )
    );

    if exists (
      select 1
      from jsonb_array_elements(p_payload -> 'games') as game
      where (game ->> 'game_date')::date <> v_target_date
    ) then
      raise exception '모든 경기 날짜는 저장 대상 날짜와 같아야 합니다';
    end if;

    select coalesce(array_agg((game ->> 'id')::integer), array[]::integer[])
    into v_keep_ids
    from jsonb_array_elements(p_payload -> 'games') as game
    where game ? 'id';

    perform id
    from public.games
    where game_date = v_target_date
    for update;

    select coalesce(jsonb_agg(to_jsonb(g) order by g.id), '[]'::jsonb)
    into v_before
    from public.games g
    where g.game_date = v_target_date;

    if exists (
      select 1
      from public.games g
      join public.markets m on m.game_id = g.id
      where g.game_date = v_target_date
        and not (g.id = any(v_keep_ids))
    ) then
      raise exception '연결된 마켓이 있는 경기는 이 화면에서 삭제할 수 없습니다';
    end if;

    with deleted as (
      delete from public.games g
      where g.game_date = v_target_date
        and not (g.id = any(v_keep_ids))
      returning g.id
    )
    select coalesce(array_agg(id), array[]::integer[])
    into v_deleted_ids
    from deleted;

    for v_game in
      select value
      from jsonb_array_elements(p_payload -> 'games')
    loop
      if v_game ? 'id' then
        v_game_id := (v_game ->> 'id')::integer;
        update public.games
        set
          game_date = (v_game ->> 'game_date')::date,
          game_time = nullif(v_game ->> 'game_time', '')::time,
          home_team_id = (v_game ->> 'home_team_id')::integer,
          away_team_id = (v_game ->> 'away_team_id')::integer,
          home_pitcher = nullif(v_game ->> 'home_pitcher', ''),
          away_pitcher = nullif(v_game ->> 'away_pitcher', ''),
          home_score = nullif(v_game ->> 'home_score', '')::integer,
          away_score = nullif(v_game ->> 'away_score', '')::integer,
          game_status = (v_game ->> 'game_status')::public.game_status,
          updated_at = now()
        where id = v_game_id
          and game_date = v_target_date;

        if not found then
          raise exception '경기를 찾을 수 없습니다: %', v_game_id;
        end if;
      else
        insert into public.games (
          game_date,
          game_time,
          home_team_id,
          away_team_id,
          home_pitcher,
          away_pitcher,
          home_score,
          away_score,
          game_status
        )
        values (
          (v_game ->> 'game_date')::date,
          nullif(v_game ->> 'game_time', '')::time,
          (v_game ->> 'home_team_id')::integer,
          (v_game ->> 'away_team_id')::integer,
          nullif(v_game ->> 'home_pitcher', ''),
          nullif(v_game ->> 'away_pitcher', ''),
          nullif(v_game ->> 'home_score', '')::integer,
          nullif(v_game ->> 'away_score', '')::integer,
          (v_game ->> 'game_status')::public.game_status
        )
        returning id into v_game_id;
        v_inserted_ids := array_append(v_inserted_ids, v_game_id);
      end if;
    end loop;

    select coalesce(jsonb_agg(to_jsonb(g) order by g.id), '[]'::jsonb)
    into v_after
    from public.games g
    where g.game_date = v_target_date;

    perform public.admin_write_audit(
      p_operator_id,
      'ADMIN_GAMES_SAVED',
      'game',
      v_target_date::text,
      v_before,
      jsonb_build_object(
        'games', v_after,
        'insertedIds', v_inserted_ids,
        'deletedIds', v_deleted_ids
      ),
      true,
      null,
      p_ip_address,
      p_user_agent
    );

    return jsonb_build_object(
      'success', true,
      'insertedIds', to_jsonb(v_inserted_ids),
      'deletedIds', to_jsonb(v_deleted_ids)
    );
  exception
    when others then
      get stacked diagnostics v_error = message_text;
      perform public.admin_write_audit(
        p_operator_id,
        case
          when v_action = 'create_teams' then 'ADMIN_TEAMS_CREATED'
          else 'ADMIN_GAMES_SAVED'
        end,
        case
          when v_action = 'create_teams' then 'team'
          else 'game'
        end,
        coalesce(v_target_date::text, null),
        v_before,
        null,
        false,
        v_error,
        p_ip_address,
        p_user_agent
      );
      return jsonb_build_object('success', false, 'error', v_error);
  end;
end;
$$;

create or replace function public.admin_create_operator(
  p_actor_id uuid,
  p_username text,
  p_display_name text,
  p_role public.admin_role,
  p_password_hash text,
  p_ip_address inet,
  p_user_agent text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_operator public.admin_operators;
  v_after jsonb;
  v_error text;
begin
  begin
    perform 1
    from public.admin_operators
    where id = p_actor_id
      and is_active
      and not must_change_password
      and role = 'OWNER'
    for update;
    if not found then
      raise exception 'OWNER 권한이 필요합니다';
    end if;

    insert into public.admin_operators (
      username,
      display_name,
      role,
      password_hash,
      created_by
    )
    values (
      p_username,
      p_display_name,
      p_role,
      p_password_hash,
      p_actor_id
    )
    returning * into v_operator;

    v_after := jsonb_build_object(
      'id', v_operator.id,
      'username', v_operator.username,
      'display_name', v_operator.display_name,
      'role', v_operator.role,
      'is_active', v_operator.is_active,
      'must_change_password', v_operator.must_change_password,
      'last_login_at', v_operator.last_login_at,
      'created_at', v_operator.created_at,
      'updated_at', v_operator.updated_at
    );

    perform public.admin_write_audit(
      p_actor_id,
      'ADMIN_OPERATOR_CREATED',
      'admin_operator',
      v_operator.id::text,
      null,
      v_after,
      true,
      null,
      p_ip_address,
      p_user_agent
    );
    return jsonb_build_object('success', true, 'operator', v_after);
  exception
    when others then
      get stacked diagnostics v_error = message_text;
      perform public.admin_write_audit(
        p_actor_id,
        'ADMIN_OPERATOR_CREATED',
        'admin_operator',
        null,
        null,
        null,
        false,
        v_error,
        p_ip_address,
        p_user_agent
      );
      return jsonb_build_object('success', false, 'error', v_error);
  end;
end;
$$;

create or replace function public.admin_update_operator(
  p_actor_id uuid,
  p_operator_id uuid,
  p_updates jsonb,
  p_ip_address inet,
  p_user_agent text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_before public.admin_operators;
  v_after public.admin_operators;
  v_before_json jsonb;
  v_after_json jsonb;
  v_error text;
  v_new_role public.admin_role;
  v_new_is_active boolean;
  v_new_must_change_password boolean;
begin
  begin
    lock table public.admin_operators in share row exclusive mode;

    if not exists (
      select 1
      from public.admin_operators
      where id = p_actor_id
        and is_active
        and not must_change_password
        and role = 'OWNER'
    ) then
      raise exception 'OWNER 권한이 필요합니다';
    end if;

    select *
    into v_before
    from public.admin_operators
    where id = p_operator_id
    for update;
    if not found then
      raise exception '운영자를 찾을 수 없습니다';
    end if;

    v_new_role := coalesce(
      (p_updates ->> 'role')::public.admin_role,
      v_before.role
    );
    v_new_is_active := coalesce(
      (p_updates ->> 'is_active')::boolean,
      v_before.is_active
    );
    v_new_must_change_password := case
      when p_updates ? 'password_hash' then true
      else v_before.must_change_password
    end;

    if v_before.role = 'OWNER'
      and v_before.is_active
      and not v_before.must_change_password
      and (
        v_new_role <> 'OWNER'
        or not v_new_is_active
        or v_new_must_change_password
      )
      and (
        select count(*)
        from public.admin_operators
        where role = 'OWNER'
          and is_active
          and not must_change_password
      ) <= 1
    then
      raise exception '마지막 활성 OWNER는 변경하거나 비활성화할 수 없습니다';
    end if;

    update public.admin_operators
    set
      display_name = coalesce(
        p_updates ->> 'display_name',
        display_name
      ),
      role = v_new_role,
      is_active = v_new_is_active,
      password_hash = coalesce(
        p_updates ->> 'password_hash',
        password_hash
      ),
      must_change_password = case
        when p_updates ? 'password_hash' then true
        else must_change_password
      end,
      password_changed_at = case
        when p_updates ? 'password_hash' then now()
        else password_changed_at
      end
    where id = p_operator_id
    returning * into v_after;

    if not v_after.is_active or p_updates ? 'password_hash' then
      update public.admin_sessions
      set revoked_at = now()
      where operator_id = p_operator_id
        and revoked_at is null;
    end if;

    v_before_json := jsonb_build_object(
      'id', v_before.id,
      'username', v_before.username,
      'display_name', v_before.display_name,
      'role', v_before.role,
      'is_active', v_before.is_active,
      'must_change_password', v_before.must_change_password,
      'last_login_at', v_before.last_login_at,
      'created_at', v_before.created_at,
      'updated_at', v_before.updated_at
    );
    v_after_json := jsonb_build_object(
      'id', v_after.id,
      'username', v_after.username,
      'display_name', v_after.display_name,
      'role', v_after.role,
      'is_active', v_after.is_active,
      'must_change_password', v_after.must_change_password,
      'last_login_at', v_after.last_login_at,
      'created_at', v_after.created_at,
      'updated_at', v_after.updated_at
    );

    perform public.admin_write_audit(
      p_actor_id,
      'ADMIN_OPERATOR_UPDATED',
      'admin_operator',
      p_operator_id::text,
      v_before_json,
      v_after_json,
      true,
      null,
      p_ip_address,
      p_user_agent
    );
    return jsonb_build_object('success', true, 'operator', v_after_json);
  exception
    when others then
      get stacked diagnostics v_error = message_text;
      perform public.admin_write_audit(
        p_actor_id,
        'ADMIN_OPERATOR_UPDATED',
        'admin_operator',
